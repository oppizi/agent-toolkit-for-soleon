#!/usr/bin/env python3
"""Keep a developer's LIVE toolkit checkout current, and build the prod copy from it.

    python3 harness/dev_live.py sync          # fast-forward to origin/main, rebuild the prod copy
    python3 harness/dev_live.py prod-copy     # rebuild the prod copy only
    python3 harness/dev_live.py status        # what is live, and how far behind origin/main

The live loop (CLAUDE.md, "Developing the toolkit"): the `agent-toolkit-for-soleon` marketplace is
added from a LOCAL checkout of this repo instead of GitHub. Its plugin entry is a
relative path (`./plugins/soleon`), and Claude Code loads such a plugin IN PLACE
(code.claude.com/docs/en/plugins/loading.md, "In-place and copied plugins"), so
an edit there takes effect on `/reload-plugins` with no version bump and no
publish. This script is run from inside that checkout (the repo it lives in).

The prod copy is the same plugin under the name `soleon-prod`, pointed at the
prod server, written as its own one-plugin marketplace (default
~/.claude/soleon-prod-marketplace). It is generated, never hand-edited: a hand
copy of 1.0.9 sat unchanged from 2026-11-02 while the plugin reached 1.0.30.

`sync` refuses to move a checkout that has local changes or is not on the
`live` branch; it never discards work. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Optional

REPO = Path(__file__).resolve().parents[1]
PLUGIN = REPO / "plugins" / "soleon"
LIVE_BRANCH = "live"
PROD_URL = "https://mcp.oppizi.com/mcp"
PROD_NAME = "soleon-prod"
DEFAULT_PROD_DIR = Path.home() / ".claude" / "soleon-prod-marketplace"
#: Never copied into the prod copy: bytecode and editor droppings.
_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store")


def git(*args: str, repo: Path = REPO) -> str:
    out = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit("git {} failed: {}".format(" ".join(args), out.stderr.strip()))
    return out.stdout.strip()


def plugin_version(plugin: Path = PLUGIN) -> str:
    return json.loads((plugin / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))["version"]


def build_prod_copy(dest: Path, plugin: Path = PLUGIN) -> Path:
    """Write `dest` as a one-plugin marketplace holding `soleon-prod`: the plugin
    files verbatim, with only its name, description and server pointed at prod."""
    target = dest / "plugins" / PROD_NAME
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(plugin, target, ignore=_IGNORE)

    manifest_path = target / ".claude-plugin" / "plugin.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["name"] = PROD_NAME
    manifest["description"] = "PROD copy (soleon.oppizi.com), generated by harness/dev_live.py. " + manifest.get("description", "")
    server = manifest.setdefault("userConfig", {}).setdefault("server_url", {})
    server["default"] = PROD_URL
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    mcp_path = target / ".mcp.json"
    mcp = json.loads(mcp_path.read_text(encoding="utf-8"))
    for entry in mcp.get("mcpServers", {}).values():
        entry["url"] = PROD_URL  # literal: no reader of the copy may fall back to dev
    mcp_path.write_text(json.dumps(mcp, indent=2) + "\n", encoding="utf-8")

    market_dir = dest / ".claude-plugin"
    market_dir.mkdir(parents=True, exist_ok=True)
    (market_dir / "marketplace.json").write_text(json.dumps({
        "name": PROD_NAME,
        "owner": {"name": "Generated from agent-toolkit-for-soleon by harness/dev_live.py"},
        "plugins": [{"name": PROD_NAME, "source": "./plugins/" + PROD_NAME,
                     "description": "Soleon plugin pointed at PROD"}],
    }, indent=2) + "\n", encoding="utf-8")
    return target


def status() -> dict:
    git("fetch", "--quiet", "origin", "main")
    return {
        "checkout": str(REPO),
        "branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "head": git("rev-parse", "--short", "HEAD"),
        "version": plugin_version(),
        "behind_origin_main": int(git("rev-list", "--count", "HEAD..origin/main")),
        "local_changes": bool(git("status", "--porcelain")),
    }


def sync(prod_dir: Optional[Path]) -> dict:
    before = status()
    if before["branch"] != LIVE_BRANCH:
        raise SystemExit("refusing to sync: {} is on {!r}, not {!r}. A live checkout only follows "
                         "origin/main; develop on a branch in another worktree, or switch back with "
                         "`git checkout {}`.".format(REPO, before["branch"], LIVE_BRANCH, LIVE_BRANCH))
    if before["local_changes"]:
        raise SystemExit("refusing to sync: {} has local changes (commit or move them first; "
                         "nothing was touched).".format(REPO))
    if before["behind_origin_main"]:
        git("merge", "--ff-only", "--quiet", "origin/main")
    after = status()
    out = {"from": before["version"], "to": after["version"], "head": after["head"],
           "moved": before["head"] != after["head"]}
    if prod_dir is not None:
        out["prod_copy"] = str(build_prod_copy(prod_dir))
    return out


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=("sync", "prod-copy", "status"))
    ap.add_argument("--prod-dir", type=Path, default=DEFAULT_PROD_DIR,
                    help="where the prod copy's marketplace lives (default: %(default)s)")
    ap.add_argument("--no-prod-copy", action="store_true", help="sync: skip the prod copy")
    opts = ap.parse_args(argv)
    if opts.command == "status":
        result = status()
    elif opts.command == "prod-copy":
        result = {"prod_copy": str(build_prod_copy(opts.prod_dir)), "version": plugin_version()}
    else:
        result = sync(None if opts.no_prod_copy else opts.prod_dir)
    print(json.dumps(result, indent=2))
    if opts.command != "status":
        print("Run /reload-plugins in Claude Code to load it.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
