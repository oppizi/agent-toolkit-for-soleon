"""Bundle copies must be the catalogue, byte for byte.

A plugin manifest cannot reference anything outside its own root, and cross-
directory symlinks are skipped on local-path and `--plugin-dir` installs — so a
capability shared by two bundles travels as a real COPY, generated by
`harness/sync_bundles.py` (see its docstring for the full reasoning).

Copies buy correctness at every install path and pay for it with one hazard: an
edit made to a bundle copy instead of the catalogue is silently destroyed by the
next sync. This module is what makes that hazard loud. Upstream
(`aws/agent-toolkit-for-aws`) relies on CI for the same guard; this repo has none,
so these tests are the only thing standing between a hand-edited copy and a lost
change.

The always-run half needs nothing but the checkout. The positive controls operate
on a throwaway `copytree` clone, so they prove `--check` is FALSIFIABLE — a drift
guard that cannot fail is not a guard, the same standard `test_validator_negative`
holds the offline validator to.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

BET_ROOT = Path(__file__).resolve().parents[2]
PLUGINS_DIR = BET_ROOT / "plugins"
SCRIPT = BET_ROOT / "harness" / "sync_bundles.py"

sys.path.insert(0, str(BET_ROOT / "harness"))
from sync_bundles import (  # noqa: E402
    HOOK_ENTRY,
    KINDS,
    bundles,
    catalogue_index,
    entries_match,
    subscriptions,
)

BUNDLES = [p.name for p in bundles()]
KIND_NAMES = sorted(KINDS)


def _run(*args: str, cwd: Path = BET_ROOT) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(cwd / "harness" / "sync_bundles.py"), *args],
        cwd=cwd, capture_output=True, text=True, check=False,
    )


# ---------------------------------------------------------------------------
# Always runs against the real checkout.
# ---------------------------------------------------------------------------


def test_repo_is_in_sync_with_the_catalogue():
    """Shells out rather than calling `sync_bundle()` directly, so the CLI — the
    thing a maintainer and the bundle-plugin skill actually invoke — is under test,
    exit code included."""
    proc = _run("--check")
    assert proc.returncode == 0, (
        f"bundles have drifted from the catalogue:\n{proc.stderr}\n{proc.stdout}"
    )


def test_check_writes_nothing():
    """`--check` is used in the middle of a test run and by the skill's Step 1; if
    it mutated the tree it would mask the very drift it reports."""
    before = {
        p: p.stat().st_mtime_ns
        for p in PLUGINS_DIR.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }
    _run("--check")
    after = {
        p: p.stat().st_mtime_ns
        for p in PLUGINS_DIR.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }
    assert before == after


@pytest.mark.parametrize("bundle_name", BUNDLES)
@pytest.mark.parametrize("kind_name", KIND_NAMES)
def test_every_subscription_matches_its_catalogue_entry(bundle_name, kind_name):
    kind = KINDS[kind_name]
    index = catalogue_index(kind)
    bundle = PLUGINS_DIR / bundle_name
    for name in subscriptions(bundle, kind, index):
        assert entries_match(index[name], kind.entry_path(bundle, name)), (
            f"{bundle_name}/{kind_name}/{name} differs from plugins/{kind_name}/{name} "
            f"— edit the catalogue copy, then run `python3 harness/sync_bundles.py`"
        )


@pytest.mark.parametrize("bundle_name", BUNDLES)
@pytest.mark.parametrize("kind_name", KIND_NAMES)
def test_no_orphaned_entries(bundle_name, kind_name):
    """Every entry in a bundle either matches a catalogue name or is deliberately
    bundle-private. Today the repo has no bundle-private capabilities, so an
    unmatched entry means a catalogue entry was deleted or renamed out from under
    a subscriber — which `--check` cannot see, because an entry with no catalogue
    match is left alone by design."""
    kind = KINDS[kind_name]
    root = PLUGINS_DIR / bundle_name / kind_name
    if not root.is_dir():
        return
    index = catalogue_index(kind)
    present = {
        kind.entry_name(p)
        for p in root.iterdir()
        if (p.is_dir() if kind.is_dir else p.name.endswith(kind.suffix))
    }
    assert not (present - set(index)), (
        f"{bundle_name}/{kind_name} has entries with no catalogue source: "
        f"{sorted(present - set(index))}"
    )


@pytest.mark.parametrize("bundle_name", BUNDLES)
def test_manifest_hooks_array_matches_subscriptions(bundle_name):
    """Only `hooks/hooks.json` is auto-discovered — there is no `hooks/*.json`
    scan — so a copied hook that is not listed in `plugin.json` is inert, and a
    listed one that is not copied is a dangling path. Both fail silently at
    runtime, which is why this is asserted rather than trusted."""
    bundle = PLUGINS_DIR / bundle_name
    manifest = json.loads((bundle / ".claude-plugin/plugin.json").read_text())
    declared = manifest.get("hooks", [])
    if not isinstance(declared, list):
        pytest.skip(f"{bundle_name} uses the inline-object hooks form")

    index = catalogue_index(KINDS["hooks"])
    expected = {HOOK_ENTRY.format(name=n) for n in subscriptions(bundle, KINDS["hooks"], index)}
    ours = {e for e in declared if e in {HOOK_ENTRY.format(name=n) for n in index}}
    assert ours == expected, (
        f"{bundle_name} declares catalogue hooks {sorted(ours)} but subscribes to "
        f"{sorted(expected)}"
    )
    for entry in declared:
        assert entry.startswith("./"), (
            f"{bundle_name} hooks entry {entry!r} must be plugin-root relative and "
            "start with './' — the manifest schema rejects anything else"
        )
        assert (bundle / entry).is_file(), f"{bundle_name} hooks entry {entry!r} does not resolve"


@pytest.mark.parametrize("kind_name", KIND_NAMES)
def test_catalogue_is_not_mistaken_for_a_bundle(kind_name):
    root = PLUGINS_DIR / kind_name
    assert root.is_dir(), f"plugins/{kind_name}/ is missing — the catalogue kinds are fixed"
    assert not (root / ".claude-plugin/plugin.json").exists(), (
        f"plugins/{kind_name}/ must not carry a plugin manifest — every bundle "
        "enumeration in this suite identifies bundles by manifest presence, so a "
        "manifest here would make the catalogue a fourth plugin"
    )
    assert (root / "README.md").is_file(), (
        f"plugins/{kind_name}/README.md documents the per-kind runtime mechanics, "
        "and is also what lets git track the directory while it is empty"
    )


def test_no_symlinks_under_plugins():
    """Copies, deliberately, not links: cross-directory symlinks are dereferenced
    only by a marketplace install that git-clones the repo. Per the plugin
    reference, "for plugins installed with `--plugin-dir` or from a local path,
    only symlinks that resolve within the plugin's own directory are preserved.
    All others are skipped." A link that crept back in would silently ship a
    bundle with a missing capability."""
    links = [p.relative_to(BET_ROOT) for p in PLUGINS_DIR.rglob("*") if p.is_symlink()]
    assert not links, f"symlinks under plugins/: {links}"


