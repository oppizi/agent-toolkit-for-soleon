@pytest.fixture()
def clone(tmp_path):
    """A throwaway copy of the repo tree the script reads: plugins/ + harness/."""
    dest = tmp_path / "repo"
    (dest / "harness").mkdir(parents=True)
    shutil.copy2(SCRIPT, dest / "harness" / "sync_bundles.py")
    shutil.copytree(
        PLUGINS_DIR, dest / "plugins",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    assert _run("--check", cwd=dest).returncode == 0, "clone should start in sync"
    return dest


def test_check_catches_a_mutated_bundle_copy(clone):
    copy = clone / "plugins/admin/skills/write-evals/SKILL.md"
    copy.write_text(copy.read_text(encoding="utf-8") + "\ntampered\n", encoding="utf-8")

    proc = _run("--check", cwd=clone)
    assert proc.returncode == 1
    assert "admin: skills/write-evals" in proc.stderr
    # The remediation must name the CATALOGUE, not the copy — pointing a
    # maintainer at the file that is about to be overwritten is worse than silence.
    assert "plugins/skills/write-evals" in proc.stderr


def test_check_catches_a_missing_file_in_a_bundle_copy(clone):
    (clone / "plugins/builder/skills/deploy-agent/assets/engine.py").unlink()
    assert _run("--check", cwd=clone).returncode == 1


def test_check_catches_an_extra_file_in_a_bundle_copy(clone):
    (clone / "plugins/builder/skills/write-evals/EXTRA.md").write_text("x", encoding="utf-8")
    assert _run("--check", cwd=clone).returncode == 1


def test_sync_repairs_every_mutation(clone):
    copy = clone / "plugins/admin/skills/write-evals/SKILL.md"
    copy.write_text("tampered", encoding="utf-8")
    (clone / "plugins/builder/skills/write-evals/EXTRA.md").write_text("x", encoding="utf-8")

    assert _run(cwd=clone).returncode == 0
    assert _run("--check", cwd=clone).returncode == 0
    assert copy.read_text(encoding="utf-8") == (
        clone / "plugins/skills/write-evals/SKILL.md"
    ).read_text(encoding="utf-8")
    assert not (clone / "plugins/builder/skills/write-evals/EXTRA.md").exists()


def test_hooks_round_trip_generates_and_removes_the_manifest_entry(clone):
    """The hooks path ships before any real hook exists, so it gets a synthetic
    one here rather than going out unexercised."""
    entry = clone / "plugins/hooks/demo-guard"
    entry.mkdir(parents=True)
    (entry / "hooks.json").write_text(
        json.dumps({
            "description": "demo",
            "hooks": {"PreToolUse": [{"matcher": "Bash", "hooks": [
                {"type": "command",
                 "command": 'bash "${CLAUDE_PLUGIN_ROOT}/hooks/demo-guard/check.sh"'},
            ]}]},
        }, indent=2) + "\n",
        encoding="utf-8",
    )
    (entry / "check.sh").write_text("#!/bin/bash\nexit 0\n", encoding="utf-8")

    manifest = clone / "plugins/builder/.claude-plugin/plugin.json"
    before = json.loads(manifest.read_text())
    assert "hooks" not in before

    assert _run("--add", "builder", "hooks", "demo-guard", cwd=clone).returncode == 0
    after = json.loads(manifest.read_text())
    assert after["hooks"] == ["./hooks/demo-guard/hooks.json"]
    assert (clone / "plugins/builder/hooks/demo-guard/check.sh").is_file()
    # Everything else in the manifest survives the rewrite.
    assert {k: v for k, v in after.items() if k != "hooks"} == before
    assert _run("--check", cwd=clone).returncode == 0

    assert _run("--remove", "builder", "hooks", "demo-guard", cwd=clone).returncode == 0
    assert json.loads(manifest.read_text()) == before
    assert not (clone / "plugins/builder/hooks").exists()


def test_check_catches_a_hand_edited_hooks_array(clone):
    manifest = clone / "plugins/hooks/demo/hooks.json"
    manifest.parent.mkdir(parents=True)
    manifest.write_text(json.dumps({"hooks": {}}) + "\n", encoding="utf-8")
    assert _run("--add", "admin", "hooks", "demo", cwd=clone).returncode == 0

    plugin_json = clone / "plugins/admin/.claude-plugin/plugin.json"
    doc = json.loads(plugin_json.read_text())
    doc["hooks"] = []  # a maintainer "cleaning up" the generated array
    plugin_json.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    proc = _run("--check", cwd=clone)
    assert proc.returncode == 1
    assert "`hooks` array" in proc.stderr


def test_add_rejects_unknown_bundle_kind_and_entry(clone):
    for args in (
        ("--add", "nope", "skills", "write-evals"),
        ("--add", "admin", "widgets", "write-evals"),
        ("--add", "admin", "skills", "no-such-skill"),
    ):
        proc = _run(*args, cwd=clone)
        assert proc.returncode == 2, f"{args} should be an operator error, got {proc.returncode}"
        assert "ERROR" in proc.stderr


def test_add_is_idempotent_and_remove_is_reversible(clone):
    assert _run("--add", "observer", "skills", "write-evals", cwd=clone).returncode == 0
    assert (clone / "plugins/observer/skills/write-evals/SKILL.md").is_file()

    proc = _run("--add", "observer", "skills", "write-evals", cwd=clone)
    assert proc.returncode == 0 and "already subscribes" in proc.stdout

    assert _run("--remove", "observer", "skills", "write-evals", cwd=clone).returncode == 0
    assert not (clone / "plugins/observer/skills").exists()
    assert _run("--check", cwd=clone).returncode == 0


def test_bundle_private_entries_are_left_alone(clone):
    """An entry with no catalogue match is legitimate and must survive a sync
    untouched — otherwise a bundle could never carry anything of its own."""
    private = clone / "plugins/observer/skills/observer-only"
    private.mkdir(parents=True)
    (private / "SKILL.md").write_text(
        "---\nname: observer-only\ndescription: private.\n---\nbody\n", encoding="utf-8"
    )
    assert _run(cwd=clone).returncode == 0
    assert (private / "SKILL.md").read_text(encoding="utf-8").endswith("body\n")
    assert _run("--check", cwd=clone).returncode == 0
